#include <iostream>
#include <cstring>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                    Статичні поля і статичні методи
==========================================================================================================================================

  Статичні поля та методи використовуються для створення даних та логіки, які належать самому класу в цілому, а не конкретним його об'єктам.
  Завдяки цьому статичні поля існують в єдиному екземплярі в пам'яті для всього додатка (методи і так завжди існують в одному екземплярі).

  Основні сценарії використання:
  -  Лічильники об'єктів: Щоб дізнатися, скільки об'єктів цього класу зараз створено.
  -  Глобальні константи класу: Наприклад, математичні сталі чи налаштування (швидкість світла, максимальний розмір масиву), які є спільними
  для всіх об'єктів класу.
  -  Спільні ресурси: Наприклад, спільний пул з'єднань з базою даних.

  Особливості статичних полів:
     - існує в одному екземплярі, спільному для всіх об'єктів класу;
     - існує навіть тоді, коли не створено жодного об'єкта;
     - не входить у sizeof об'єкта.

  Особливості статичного методу:
     - має доступ ЛИШЕ до статичних полів і статичних методів.
     - статичний метод не прив'язаний до жодного об'єкта.
*/

class Student
{
private:
    static int count;                  // скільки об'єктів існує зараз
    static int nextId;                 // останній виданий номер

    // статичні поля також можна визначити безпосередньо в класі за допомогою inline
    //inline static int count = 0;
    //inline static int nextId = 1000;

    const int id;
    char* name;

public:
    Student(const char* newName) : id(++nextId), name(nullptr)   // кожен новий студент отримує унікальний номер
    {
        setName(newName);
        count++;
    }

    Student() : Student("Невідомий")   // лічильник збільшить головний конструктор
    {}

    ~Student()
    {
        count--;
        delete[] name;
    }

    void setName(const char* newName)
    {
        delete[] name;
        size_t length = strlen(newName) + 1;
        name = new char[length];
        strcpy_s(name, length, newName);
    }

    void print()
    {
        // Звичайний метод бачить і свої поля, і статичні
        cout << "#" << id << " " << name << " (усього студентів: " << count << ")" << endl;
    }

    // Статичний метод: доступ лише до статичних членів
    static int getCount()
    {
        // return id;   // ПОМИЛКА: id належить об'єкту, а об'єкта тут немає
        return count;
    }
};

// Визначення статичних полів поза класом — обов'язково, інакше помилка компонувальника
int Student::count = 0;
int Student::nextId = 1000;

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    // Статичний метод можна викликати, коли ще немає жодного об'єкта
    cout << "На початку: " << Student::getCount() << endl;

    Student a("Олена");
    Student b("Ігор");
    a.print();
    b.print();

    {
        Student c;
        c.print();
        cout << "У блоці: " << Student::getCount() << endl;
    }   // c знищено, лічильник зменшився

    cout << "Після блоку: " << Student::getCount() << endl;

    Student* group = new Student[3];
    cout << "З динамічним масивом: " << Student::getCount() << endl;
    delete[] group;
    cout << "Після delete[]: " << Student::getCount() << endl;

    // Статичне поле не входить у розмір об'єкта
    cout << "sizeof(Student) = " << sizeof(Student) << endl;

    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - Найчастіша помилка: оголосити static-поле в класі і забути визначити
    поза класом → LNK2019/LNK2001 «unresolved external symbol».
    У C++17+ цього можна уникнути: inline static int count = 0;
  - Лічильник об'єктів має збільшуватися в КОЖНОМУ конструкторі. Делегування
    гарантує це: усі шляхи створення об'єкта проходять через головний конструктор.
  - Статичні члени підкоряються специфікаторам доступу: private static-поле
    недоступне ззовні, як і звичайне.
  - Типові застосування: лічильники об'єктів, генерація унікальних id,
    спільні налаштування для всіх об'єктів класу, допоміжні методи,
    яким не потрібен об'єкт.

  ПРАКТИКА
  1. Клас Car — лічильник автомобілів.
     - private-поля: char brand[30], static int totalCars.
     - Визначте статичне поле поза класом: int Car::totalCars = 0;
     - Конструктор Car(newBrand) — копіює марку і збільшує totalCars на 1.
     - Деструктор ~Car() — зменшує totalCars на 1.
     - Статичний метод getTotalCars() — повертає totalCars.
     - Метод print() — виводить марку.
     - У main: виведіть Car::getTotalCars() ще до створення авто (має бути 0);
       створіть два авто і виведіть лічильник; створіть третє авто всередині
       блоку { } і виведіть лічильник у блоці та після нього.

  2. Клас Product — спільна знижка для всіх товарів.
     - private-поля: char name[50], int price, static int discount (знижка у відсотках).
     - Визначте статичне поле поза класом: int Product::discount = 0;
     - Конструктор Product(newName, newPrice) — ім'я і ціна (ціну через список ініціалізації).
     - Статичний метод setDiscount(newDiscount) — приймає лише значення
       від 0 до 50, повертає bool (як setAge у Student).
     - Метод getFinalPrice() — повертає ціну зі знижкою:
       price - price * discount / 100.
     - Метод print() — виводить назву, звичайну ціну і ціну зі знижкою.
     - У main: створіть три товари і виведіть їх; викличте Product::setDiscount(20)
       і виведіть товари ще раз — знижка має змінитися в УСІХ товарів одразу;
       спробуйте встановити знижку 70 і виведіть повідомлення про помилку.
*/
