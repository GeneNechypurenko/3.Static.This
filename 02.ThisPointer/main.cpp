#include <iostream>
#include <cstring>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                             Покажчик this
==========================================================================================================================================

  Покажчик this в C++ — це прихований константний покажчик на поточний об'єкт класу, який автоматично передається в усі його НЕСТАТИЧНІ
  методи. Він зберігає адресу об'єкта, для якого було викликано метод, і дозволяє звертатися до членів цього конкретного екземпляра.

  Головні функції this:
    - Зв'язок методу з об'єктом:
  Завдяки this метод точно «знає», з полями якого саме екземпляра (об'єкта) класу він зараз працює.
    - Розрізнення імен:
  Дозволяє розділити однойменні змінні, якщо в методі ім'я параметра збігається з ім'ям поля (this->x = x).
    - Повернення поточного об'єкта:
  Використовується для повернення посилання на сам об'єкт із методу (return *this;), що дозволяє створювати ланцюжки викликів (chaining).

*/

class Student
{
private:
    char* name;
    int age;

public:
    // У списку ініціалізації конфлікту імен немає:
    // зовні дужок — поле, усередині дужок — параметр
    Student(const char* name, int age) : name(nullptr), age(age)
    {
        setName(name);
    }

    ~Student()
    {
        delete[] name;
    }

    // Параметр name «закриває» поле name, тому до поля звертаємося через this
    Student& setName(const char* name)
    {
        delete[] this->name;
        size_t length = strlen(name) + 1;
        this->name = new char[length];
        strcpy_s(this->name, length, name);
        return *this;               // повертаємо сам об'єкт
    }

    Student& setAge(int age)
    {
        if (age >= 16 && age <= 100)
        {
            this->age = age;
        }
        return *this;
    }

    void print()
    {
        cout << "  " << name << ", вік: " << age << endl;
    }

    void showThis()
    {
        cout << "  this = " << this << endl;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Student a("Олена", 20);
    Student b("Ігор", 22);

    // 1. this — адреса того об'єкта, для якого викликано метод
    cout << "&a     = " << &a << endl;
    a.showThis();
    cout << "&b     = " << &b << endl;
    b.showThis();

    // 2. Конфлікт імен розв'язано через this
    a.setAge(21);
    a.print();

    // 3. Ланцюжок викликів: кожен метод повертає *this
    b.setName("Ігор Петренко").setAge(23).print();

    return 0;
}

/*
  ІНСАЙТИ / BEST PRACTICES
  - this константний, його не можна змінити:  this = nullptr;  — помилка компіляції.
  - this — це завжди покажчик на конкретний об'єкт (екземпляр), для якого викликано метод, тому в статичних методах його немає!
    Пам'ятайте: статичний метод прив'язаний до класу, а не до об'єкта, тому не може звертатися до звичайних полів напряму!
  - this має тип данних Ім'яКласу*. У класі Student це Student*.
  - Метод для ланцюжка ЗАВЖДИ повинен повертати Student&, а не Student - повернення за значенням створює копію,
    і наступний виклик ланцюжка змінить копію, а не оригінал!
  - У реальних проєктах конфлікт імен між полями та параметрами методів часто обходять за допомогою іменуванням параметрів як
    newName, newAge	чи іменування полів як m_name, m_age або name_, age_.
    Обидва підходи нормальні — головне, у будь-якому випадку дотримуватися єдиного стилю коду у всьому проєкті.

  ПРАКТИКА
  1. Клас Box (прямокутна коробка):
     - поля: int width, int height;
     - конструктор Box(int width, int height) — параметри з тими самими
       іменами, що й поля; присвоєння через this-> у тілі конструктора;
     - методи setWidth(int width) і setHeight(int height):
         * параметри з тими самими іменами, що й поля (використовуйте this->);
         * значення приймається, лише якщо воно більше за 0 (як setAge у Student);
         * обидва методи повертають Box& (return *this);
     - метод print() — виводить ширину і висоту;
     - метод showThis() — виводить значення this.
     У main:
       а) створіть Box і виведіть його;
       б) змініть його одним ланцюжком:  box.setWidth(10).setHeight(5).print();
       в) спробуйте в ланцюжку встановити від'ємну ширину і переконайтеся,
          що вона не змінилася;
       г) створіть другу коробку і для обох порівняйте showThis() з &об'єкта.

  2. Клас Player (гравець):
     - поля: char name[30], int score, int level;
     - конструктор Player(const char* name) — ім'я копіюється через
       strcpy_s(this->name, 30, name); score = 0 і level = 1 задайте
       у списку ініціалізації;
     - метод addScore(int score) — додає очки до поля score, лише якщо
       параметр більший за 0; повертає Player&;
     - метод levelUp() — збільшує level на 1; повертає Player&;
     - метод print() — виводить:  Олена: 120 очок, рівень 2
     - метод compare(Player& other):
         * якщо this == &other — вивести «Це той самий гравець»;
         * інакше вивести ім'я гравця, у якого більше очок
           (або «Нічия», якщо очок порівну).
     У main:
       а) створіть двох гравців;
       б) першому одним ланцюжком додайте очки двічі, підвищте рівень
          і виведіть:  a.addScore(50).addScore(70).levelUp().print();
       в) другому додайте очки окремими викликами і виведіть;
       г) викличте a.compare(b) і a.compare(a).
*/
